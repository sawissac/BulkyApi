/**
 * Bundles `@types/lodash`'s `common/*.d.ts` into a single ambient `.d.ts`
 * string that Monaco can register as an extra lib, exposing a typed `lodash`
 * global to the script editor (`lodash.chunk(...)`, `lodash.cloneDeep(...)`,
 * autocomplete on every method).
 *
 * The upstream types are twelve separate module files, each shaped as:
 *
 *     import _ = require("../index");
 *     <a few outside-block helper types>
 *     declare module "../index" { <the real LoDashStatic members> }   // last line: }
 *
 * We hoist the outside-block helpers to true global scope (where `Function` /
 * `Partial` still mean the globals they alias) and merge every module block
 * into one `declare namespace LodashLib { ... }`, then declare
 * `const lodash: LodashLib.LoDashStatic`.
 *
 * Run after bumping `@types/lodash`:  node scripts/gen-lodash-editor-lib.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const common = resolve(root, "node_modules/@types/lodash/common");

// index.d.ts reference order.
const ORDER = [
  "common",
  "array",
  "collection",
  "date",
  "function",
  "lang",
  "math",
  "number",
  "object",
  "seq",
  "string",
  "util",
];

const MODULE_OPEN = /^declare module "\.\.?\/index" \{$/;

const hoisted = [];
const nsExtra = [];
const bodies = [];

for (const name of ORDER) {
  const lines = readFileSync(resolve(common, `${name}.d.ts`), "utf8").split("\n");

  const openIdx = lines.findIndex((l) => MODULE_OPEN.test(l.trim()));
  if (openIdx === -1) throw new Error(`${name}.d.ts: no 'declare module' block`);
  if (lines[lines.length - 1].trim() !== "}") {
    // Files end with a trailing newline, so the real close is the penultimate.
    if (lines[lines.length - 2].trim() !== "}")
      throw new Error(`${name}.d.ts: module block does not close on the last line`);
    lines.pop();
  }

  for (const raw of lines.slice(0, openIdx)) {
    const line = raw.trim();
    if (!line) continue;
    if (/^import\s/.test(line)) continue;
    if (/^export\s*\{\s*\}\s*;?$/.test(line)) continue;
    if (line.startsWith("//")) continue;
    if (/^export const uniqueSymbol:/.test(line)) {
      nsExtra.push("    export const uniqueSymbol: unique symbol;");
      continue;
    }
    hoisted.push(raw.replace(/^\s*export\s+/, "").replace(/\b_\./g, "LodashLib."));
  }

  // Everything between the `declare module` line and its closing `}`.
  bodies.push(
    `    // ===== ${name}.d.ts =====\n` +
      lines
        .slice(openIdx + 1, lines.length - 1)
        .join("\n"),
  );
}

const lib = [
  hoisted.join("\n"),
  "",
  "declare namespace LodashLib {",
  nsExtra.join("\n"),
  bodies.join("\n"),
  "}",
  "",
  "/** Lodash 4 utility library, injected by the Bulky script runtime. Call as",
  " *  `lodash.concat(...)`, `lodash.cloneDeep(...)`, `lodash.groupBy(...)`. */",
  "declare const lodash: LodashLib.LoDashStatic;",
  "",
].join("\n");

const out = `// AUTOGENERATED by scripts/gen-lodash-editor-lib.mjs — do not edit by hand.
// Bundled from @types/lodash so Monaco can type the \`lodash\` script global.
// eslint ignores this path (see eslint.config.mjs).

/** Ambient \`.d.ts\` text registered with Monaco as an extra lib. */
export const LODASH_EDITOR_LIB: string = ${JSON.stringify(lib)};
`;

writeFileSync(resolve(root, "src/lib/lodashEditorLib.ts"), out);
console.log("wrote src/lib/lodashEditorLib.ts");
